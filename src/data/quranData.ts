/**
 * Returns the complete content of a single surah, including all ayahs
 * with bracket-encoded tajweed text AND a merged `translation` field
 * sourced from quran-json. Both sources are ordered identically by
 * numberInSurah, so a straight index merge is safe.
 */
const surahCache = new Map<number, SurahData>();
export function readSurah(surahNumber: number): SurahData {
  if (surahCache.has(surahNumber)) return surahCache.get(surahNumber)!;

  const raw = SURAH_FILES[surahNumber] as SurahData;
  const enVerses: { translation?: string }[] =
    (EN_CHAPTER_FILES[surahNumber]?.verses) ?? [];

  const result: SurahData = {
    ...raw,
    ayahs: raw.ayahs.map((a, i) => ({ ...a, translation: enVerses[i]?.translation })),
  };

  surahCache.set(surahNumber, result);
  return result;
}

export function getSurahMeta(surahNumber: number): SurahMeta {
  const safe = Math.max(1, Math.min(114, Math.floor(surahNumber)));
  const t = SURAH_STATIC[safe - 1];
  return {
    number:                 t[0],
    name:                   t[1],
    englishName:            t[2],
    englishNameTranslation: t[3],
    numberOfAyahs:          t[4],
    revelationType:         t[5],
    juzNumber:              S2J[safe] ?? 1,
  };
}

export function getAllSurahMeta(): SurahMeta[] {
  return SURAH_STATIC.map((_, i) => getSurahMeta(i + 1));
}

export function getJuzList(): JuzEntry[] {
  return JUZ_STATIC;
}

export function stripTajweed(encoded: string): string {
  return encoded.replace(/\[[a-z]:?[0-9]*\[/g, '').replace(/\]/g, '');
}

export function surahToJuz(surahNumber: number): number {
  return S2J[surahNumber] ?? 1;
}
